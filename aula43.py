# LISTAS

# MÉTODOS UTEIS: append, insert, pop, del, clear, extend, +, *, min, max, sum, sorted, sort

#        0   1   2   3 
#       -5  -4  -3  -2
lista = [10, 20, 30, 40];

lista.append(50); # Adiciona um elemento no final da lista
print(lista); # [10, 20, 30, 40, 50]
lista.pop(); # Remove o último elemento da lista
print(lista); # [10, 20, 30, 40]
lista.insert(2, 25); # Adiciona um elemento em uma posição específica
print(lista); # [10, 20, 25, 30, 40, 50]    
